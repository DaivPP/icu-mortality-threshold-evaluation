"""
Build a feature table for early clinical deterioration prediction.

Cohort: all ICU stays in the TinyEHR / MIMIC-IV-demo dataset.
Features: summary statistics (mean, min, max) of five vital signs,
          computed ONLY from the first 24 hours of each ICU stay
          (to avoid leaking information from after the prediction point).
Label:   hospital_expire_flag (real recorded in-hospital mortality,
          from admissions.csv) -- NOT a rule-derived label.

This directly fixes the core flaw of the earlier capstone project,
where labels were generated by the same rules used as model inputs.
"""

import pandas as pd
import numpy as np
from pathlib import Path

# Point this at the TinyEHR dev mirror, OR the official PhysioNet download
# (e.g. ".../physionet.org/files/mimic-iv-demo/2.2") -- both layouts work,
# since read_table() below transparently handles plain .csv or gzipped .csv.gz.
DATA_DIR = Path("/home/claude/TinyEHR/tinyehr_mimic_format")
OUT_DIR = Path(__file__).resolve().parent.parent / "outputs"
OUT_DIR.mkdir(parents=True, exist_ok=True)


def read_table(relative_path, **kwargs):
    """Read a MIMIC-format table whether it's plain .csv (TinyEHR dev mirror)
    or gzip-compressed .csv.gz (official PhysioNet download) -- pandas infers
    compression automatically from the extension."""
    plain = DATA_DIR / relative_path
    gz = DATA_DIR / (relative_path + ".gz")
    if plain.exists():
        return pd.read_csv(plain, **kwargs)
    if gz.exists():
        return pd.read_csv(gz, **kwargs)
    raise FileNotFoundError(f"Could not find {plain} or {gz}")

FEATURE_WINDOW_HOURS = 24

# itemid -> clean feature name, confirmed against icu/d_items.csv
VITAL_ITEMS = {
    220045: "heart_rate",
    220179: "sbp",           # non-invasive systolic BP
    220180: "dbp",           # non-invasive diastolic BP
    220210: "resp_rate",
    220277: "spo2",
}
# two temperature items (F and C) -- we'll load both and convert F->C
TEMP_F_ITEM = 223761
TEMP_C_ITEM = 223762


def load_cohort():
    """Build the base cohort: one row per ICU stay, with demographics and the real outcome label."""
    icustays = read_table("icu/icustays.csv", parse_dates=["intime", "outtime"])
    admissions = read_table("hosp/admissions.csv", parse_dates=["admittime", "dischtime"])
    patients = read_table("hosp/patients.csv")

    cohort = icustays.merge(
        admissions[["hadm_id", "hospital_expire_flag", "admission_type", "insurance"]],
        on="hadm_id", how="left",
    )
    cohort = cohort.merge(patients[["subject_id", "gender", "anchor_age"]], on="subject_id", how="left")

    # Keep only the FIRST ICU stay per admission, to avoid one hospitalization
    # contributing multiple correlated rows.
    cohort = cohort.sort_values("intime").drop_duplicates(subset="hadm_id", keep="first")

    return cohort.reset_index(drop=True)


def load_vitals_window(cohort):
    """For each ICU stay, pull chartevents in the first FEATURE_WINDOW_HOURS and
    summarize each vital sign as mean/min/max. Only uses data up to the window
    cutoff -- never anything from later in the stay."""
    usecols = ["subject_id", "stay_id", "charttime", "itemid", "valuenum"]
    chart_iter = read_table(
        "icu/chartevents.csv",
        usecols=usecols,
        parse_dates=["charttime"],
        chunksize=500_000,
    )

    all_item_ids = set(VITAL_ITEMS) | {TEMP_F_ITEM, TEMP_C_ITEM}
    stay_intime = cohort.set_index("stay_id")["intime"].to_dict()
    valid_stays = set(stay_intime.keys())

    rows = []
    for chunk in chart_iter:
        chunk = chunk[chunk["itemid"].isin(all_item_ids) & chunk["stay_id"].isin(valid_stays)]
        if chunk.empty:
            continue
        chunk = chunk.dropna(subset=["valuenum"])
        chunk["intime"] = chunk["stay_id"].map(stay_intime)
        chunk["hours_from_admit"] = (chunk["charttime"] - chunk["intime"]).dt.total_seconds() / 3600
        chunk = chunk[(chunk["hours_from_admit"] >= 0) & (chunk["hours_from_admit"] <= FEATURE_WINDOW_HOURS)]
        if not chunk.empty:
            rows.append(chunk)

    if not rows:
        raise RuntimeError("No chartevents matched the target items/window -- check item ids.")

    vitals = pd.concat(rows, ignore_index=True)

    # Normalize temperature to Celsius, tag with a single "temp_c" feature name
    vitals["feature_name"] = vitals["itemid"].map(VITAL_ITEMS)
    temp_f_mask = vitals["itemid"] == TEMP_F_ITEM
    vitals.loc[temp_f_mask, "valuenum"] = (vitals.loc[temp_f_mask, "valuenum"] - 32) * 5.0 / 9.0
    vitals.loc[vitals["itemid"].isin([TEMP_F_ITEM, TEMP_C_ITEM]), "feature_name"] = "temp_c"

    return vitals


def summarize_vitals(vitals):
    """Pivot to one row per stay_id, with mean/min/max per vital."""
    agg = vitals.groupby(["stay_id", "feature_name"])["valuenum"].agg(["mean", "min", "max"])
    agg = agg.unstack("feature_name")
    agg.columns = [f"{feat}_{stat}" for stat, feat in agg.columns]
    return agg.reset_index()


def main():
    cohort = load_cohort()
    print(f"Cohort size (one row per admission's first ICU stay): {len(cohort)}")
    print(f"Mortality label distribution:\n{cohort['hospital_expire_flag'].value_counts()}")

    vitals = load_vitals_window(cohort)
    feat = summarize_vitals(vitals)

    final = cohort.merge(feat, on="stay_id", how="left")

    feature_cols = [c for c in final.columns if any(
        c.startswith(p) for p in ["heart_rate", "sbp", "dbp", "resp_rate", "spo2", "temp_c"]
    )]
    n_missing = final[feature_cols].isna().all(axis=1).sum()
    print(f"\nStays with NO vitals in the first {FEATURE_WINDOW_HOURS}h window: {n_missing}")

    out_path = OUT_DIR / "feature_table.csv"
    final.to_csv(out_path, index=False)
    print(f"\nSaved feature table -> {out_path}")
    print(f"Shape: {final.shape}")
    print(f"Feature columns: {feature_cols}")

    return final


if __name__ == "__main__":
    main()
